begin;
create temporary table ws_test as select o.user_id owner,(select a.user_id from public.participant_access a where a.participant_id=o.participant_id and a.user_id<>o.user_id and a.can_write limit 1) colleague,null::uuid pid,null::uuid rid,null::uuid cid,null::text email from private.tracker_owners o limit 1;
update ws_test set email=(select email from auth.users where id=colleague);
grant select,update on ws_test to authenticated;
select set_config('request.jwt.claims',json_build_object('sub',owner,'role','authenticated')::text,true) from ws_test;
set local role authenticated;
do $$declare s record; newpid uuid;newrid uuid;begin
 select * into s from ws_test;
 newpid:=public.workspace_save_client('Rollback workspace',true,true,'A focused test');
 
 update ws_test t set pid=newpid;
 perform public.workspace_team(newpid,jsonb_build_array(jsonb_build_object('email',s.email,'name','Existing colleague','role','school','tracker','none','plan','write')));
 if jsonb_array_length(public.workspace_data(newpid)->'team')<>2 then raise exception 'Team missing';end if;
 newrid:=public.workspace_publish_review(newpid,'plan','{"include":["Existing supports"],"notes":"Review this setup"}',current_date+3);
 update ws_test t set rid=newrid,cid=(select id from public.team_consultations c where c.participant_id=newpid);
 insert into public.tracker_days(participant_id,tracking_date,sleep) values(newpid,current_date,'Slept through');
end$$;
reset role;
select set_config('request.jwt.claims',json_build_object('sub',colleague,'role','authenticated')::text,true) from ws_test;
set local role authenticated;
do $$declare s record;begin select * into s from ws_test;
 if exists(select 1 from public.tracker_days where participant_id=s.pid) then raise exception 'Plan-only member saw tracker records';end if;
 if private.consultation_access(s.cid,true) then raise exception 'Preparation-stage contribution allowed';end if;
 perform public.workspace_respond(s.rid,'agree','');
 perform public.workspace_respond(s.rid,'changes','Adjust the dates');
 if jsonb_array_length(public.workspace_review(s.rid)->'responses')<>2 then raise exception 'Response history lost';end if;
 begin perform public.workspace_data(s.pid);raise exception 'Nonowner read setup';exception when insufficient_privilege then null;end;
 begin perform public.workspace_open(s.pid);raise exception 'Nonowner opened setup';exception when insufficient_privilege then null;end;
end$$;
reset role;
select set_config('request.jwt.claims',json_build_object('sub',owner,'role','authenticated')::text,true) from ws_test;
set local role authenticated;
do $$declare s record;begin select * into s from ws_test;
 perform public.workspace_publish_review(s.pid,'plan','{"notes":"Changed setup"}',current_date+4);
 if (public.workspace_review(s.rid)->>'current')::boolean then raise exception 'Old version remained current';end if;
 perform public.workspace_save_period(s.pid,'Agreed dates',current_date,current_date+5,array['mid_morning'],array[1,2,3,4,5],true,'{}',array['sleep','breakfast']);
 perform public.workspace_open(s.pid);
 if not (public.workspace_data(s.pid)->'tools'->>'opened')::boolean then raise exception 'Setup did not open';end if;
end$$;
reset role;
rollback;
